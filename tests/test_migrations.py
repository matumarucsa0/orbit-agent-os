from __future__ import annotations

from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import create_engine, inspect, text

from orbit.domain import Base
from tests.conftest import TEST_DATABASE_URL

ROOT = Path(__file__).resolve().parents[1]


def alembic_config(url: str) -> Config:
    config = Config(str(ROOT / "alembic.ini"))
    config.set_main_option("script_location", str(ROOT / "migrations"))
    config.set_main_option("sqlalchemy.url", url.replace("%", "%%"))
    return config


@pytest.fixture
def empty_db_url(tmp_path: Path) -> str:
    """A file SQLite DB, or the (emptied) test database when the suite runs on Postgres."""
    if TEST_DATABASE_URL.startswith("sqlite"):
        return f"sqlite:///{(tmp_path / 'orbit.db').as_posix()}"
    engine = create_engine(TEST_DATABASE_URL)
    Base.metadata.drop_all(engine)
    with engine.begin() as conn:
        conn.execute(text("DROP TABLE IF EXISTS alembic_version"))
    engine.dispose()
    return TEST_DATABASE_URL


def test_upgrade_head_and_no_model_drift(empty_db_url: str) -> None:
    config = alembic_config(empty_db_url)

    command.upgrade(config, "head")
    # Fails with AutogenerateDiffsDetected if models changed without a migration.
    command.check(config)

    engine = create_engine(empty_db_url)
    assert "alembic_version" in inspect(engine).get_table_names()
    engine.dispose()


def test_downgrade_to_base(empty_db_url: str) -> None:
    config = alembic_config(empty_db_url)
    command.upgrade(config, "head")
    command.downgrade(config, "base")
